"""Draws the agent graph from the code, as a Mermaid diagram.

    make diagrams

writes docs/architecture/03-agent-graph.generated.md. The hand-drawn design
(03-agent-graph.drawio.svg) shows the full target; this file shows what is
built today. A test fails if the file is out of date, so it always matches
the code.
"""

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from langchain_core.runnables.graph import NodeStyles

from agents.graph import build_graph
from agents.llm import LLMGateway
from agents.nodes import NodeContext
from agents.service import UnavailableSearcher
from agents.telemetry import AgentMetrics

OUTPUT = Path("docs/architecture/03-agent-graph.generated.md")

_HEADER = """\
# Agent graph (generated from the code)

Do not edit this file by hand. It is written by `make diagrams` from
[agents/graph.py](../../agents/graph.py), and a test fails when it no longer
matches the code. Dashed arrows are routing decisions; solid arrows always run.

Compare it with the design in [03-agent-graph.drawio.svg](03-agent-graph.drawio.svg).

"""

# LangGraph's default colours give light fills with no text colour, so in a
# dark editor theme the text turns light too and disappears into the pill.
# Setting the text colour and a border keeps it readable on light and dark.
_NODE_STYLES = NodeStyles(
    default="fill:#ede9fe,stroke:#6d28d9,stroke-width:1px,color:#1e1b4b,line-height:1.2",
    first="fill:#ddd6fe,stroke:#6d28d9,stroke-width:1px,color:#1e1b4b",
    last="fill:#c4b5fd,stroke:#6d28d9,stroke-width:1px,color:#1e1b4b",
)


def mermaid() -> str:
    # Drawing the graph never runs a node, so no model or index is needed.
    context = NodeContext(
        gateway=LLMGateway(providers=()),
        searcher=UnavailableSearcher("not used for drawing"),
        metrics=AgentMetrics(),
    )
    return build_graph(context).get_graph().draw_mermaid(node_colors=_NODE_STYLES)


def render() -> str:
    return f"{_HEADER}```mermaid\n{mermaid().strip()}\n```\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m agents.diagram")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    args.output.write_text(render(), encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
